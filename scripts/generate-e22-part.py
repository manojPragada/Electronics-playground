#!/usr/bin/env python3
"""Generate the E22 LoRa module part (frontend/public/parts/index.json entry).

The module is the 2x6-header SX1262 breakout (Ebyte E22-style pinout, the one
that plugs into the yellow socket of common STM32 LoRa test boards). Its
simulation is the gallery's SX1262 model with the pin names the real module
prints: RESET is called NRST, and DIO2/TXEN/RXEN exist as pads.

Run:  python3 scripts/generate-e22-part.py
Then: the entry is merged into frontend/public/parts/index.json.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "frontend/src/components/customChips/examples/sx1262.c"
OUT = ROOT / "frontend/public/parts/index.json"

sys.path.insert(0, str(ROOT / "backend"))
from app.services.part_library import validate_part  # noqa: E402

W, H = 120, 236

# Pin columns follow the printed socket order, top to bottom:
#   GND  VCC / NRST NSS / SCK MOSI / MISO DIO1 / BUSY DIO2 / TXEN RXEN
LEFT = ["GND", "NRST", "SCK", "MISO", "BUSY", "TXEN"]
RIGHT = ["VCC", "NSS", "MOSI", "DIO1", "DIO2", "RXEN"]
pins = []
for i, (l, r) in enumerate(zip(LEFT, RIGHT)):
    y = 26 + i * 20
    pins.append({"name": l, "x": 22, "y": y})
    pins.append({"name": r, "x": 98, "y": y})
pins.append({"name": "ANT", "x": 60, "y": 222})  # the SMA connector: the "air" in the sim

FACE = f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}">
  <rect x="12" y="6" width="96" height="190" rx="5" fill="#1d4f9f" stroke="#12305f" stroke-width="2"/>
  <rect x="16" y="10" width="88" height="14" rx="2" fill="#173f82"/>
  <g fill="#e8c35b"><circle cx="22" cy="16" r="2"/><circle cx="98" cy="16" r="2"/></g>
  <rect x="26" y="136" width="68" height="50" rx="3" fill="#c9ced3" stroke="#8d949b" stroke-width="1.5"/>
  <rect x="32" y="142" width="22" height="22" rx="2" fill="#2b2f33"/>
  <text x="76" y="156" text-anchor="middle" font-family="monospace" font-size="9" font-weight="bold" fill="#33383d">LoRa</text>
  <text x="60" y="176" text-anchor="middle" font-family="monospace" font-size="8" fill="#4a5058">SX1262</text>
  <rect x="44" y="196" width="32" height="12" fill="#c9a227" stroke="#7a6212"/>
  <rect x="50" y="206" width="20" height="20" rx="2" fill="#d4af37" stroke="#7a6212" stroke-width="1.5"/>
  <circle cx="60" cy="222" r="6" fill="#f2d24b" stroke="#9a7d12" stroke-width="1.5"/>
</svg>"""


def patched_source() -> str:
    c = SRC.read_text(encoding="utf-8")
    assert c.count('vx_pin_register("RESET"') == 1, "sx1262.c changed: update this generator"
    c = c.replace('vx_pin_register("RESET"', 'vx_pin_register("NRST"')
    anchor = '    s->ant = vx_pin_register("ANT", VX_INPUT);\n'
    assert c.count(anchor) == 1, "sx1262.c changed: update this generator"
    extra = (
        "    /* E22 breakout pads the SX1262 core model does not use: DIO2 and the\n"
        "     * RF-switch enables. They exist so wires to them land on a real pad. */\n"
        '    (void)vx_pin_register("DIO2", VX_OUTPUT_LOW);\n'
        '    (void)vx_pin_register("TXEN", VX_INPUT);\n'
        '    (void)vx_pin_register("RXEN", VX_INPUT);\n'
    )
    c = c.replace(anchor, anchor + extra)
    head = "/* E22 module variant of sx1262.c (generated by scripts/generate-e22-part.py):\n * RESET is NRST; DIO2, TXEN and RXEN are extra pads. Model unchanged. */\n"
    return head + c


part = validate_part(
    {
        "id": "e22-lora-module",
        "name": "E22 LoRa Module (SX1262)",
        "category": "communication",
        "description": (
            "SX1262 LoRa module on a 2x6 header breakout with an SMA antenna connector, "
            "pinout GND VCC / NRST NSS / SCK MOSI / MISO DIO1 / BUSY DIO2 / TXEN RXEN. "
            "Wire the ANT pins of two modules together and frames cross between them. "
            "Models command flow only, not range or modulation."
        ),
        "tags": ["lora", "sx1262", "e22", "radio", "wireless", "module"],
        "keywords": [
            "ebyte e22 e22-900m22s e22-400m22s long range transceiver 868 915 433 mhz",
            "stm32 lora test board socket 2x6 header sma antenna radiolib",
        ],
        "pins": pins,
        "body": {"width": W, "height": H},
        "face_svg": FACE,
        "source_c": patched_source(),
    }
)

existing = {}
if OUT.is_file():
    for p in json.loads(OUT.read_text(encoding="utf-8")).get("parts", []):
        existing[p["id"]] = p
existing[part["id"]] = part
OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text(json.dumps({"parts": list(existing.values())}, indent=1), encoding="utf-8")
print(f"wrote {OUT.relative_to(ROOT)}: {len(existing)} part(s), source {len(part['source_c'])} bytes")
